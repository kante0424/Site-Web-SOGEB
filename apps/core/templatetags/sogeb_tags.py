# Icône associée à chaque valeur de la SOGEB
ICONES_VALEURS = {"passion": "flamme", "disponibilite": "casque", "rapidite": "eclair",
                  "fiabilite": "bouclier", "solidarite": "mains", "responsabilite": "feuille"}


@register.simple_tag
def icone(nom, taille=24):
    from django.utils.html import format_html
    from django.utils.safestring import mark_safe

    nom = ICONES_VALEURS.get(nom, nom)
    trace = ICONES.get(nom, ICONES["fleche"])
    return format_html(
        '<svg class="icone" width="{0}" height="{0}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
        'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">{1}</svg>',
        taille, mark_safe(trace),
    )


@register.filter
def mise_en_avant(texte):
    """Met en couleur les mots entourés d'astérisques : « Le réseau qui *relie* la Guinée »."""
    import re

    from django.utils.html import escape
    from django.utils.safestring import mark_safe

    return mark_safe(re.sub(r"\*(.+?)\*", r"<em>\1</em>", escape(texte)))


@register.filter
def sans_asterisques(texte):
    return (texte or "").replace("*", "")


@register.filter
def est_contact(page):
    """Vrai pour la page Contact, affichée en bouton à part dans l'en-tête."""
    return type(page).__name__ == "ContactPage"
